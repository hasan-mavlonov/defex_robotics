"""Audit of the escapes of the controllers that run C's VERIFY in a benchmark folder: final pose and the seat
and verify events, and wall-yaw passes with no constraint.

python -m experiments.cp2_audit results/benchmark_v0.2b > results/benchmark_v0.2b/AUDIT_TABLES.md

C and G first; J (v0.2d: F's insertion, then C's VERIFY) in its own sections, printed only when a run has J.
J has no seated candidate of C's DETECT: its seat column is F's hand-over to C's VERIFY.
"""
from __future__ import annotations

import argparse
import csv
import gzip
import json
import re
from collections import Counter
from pathlib import Path

CONTROLLERS = ("adaptive", "adaptive_learned")
J = "spiral_rcc_verify"
LABEL = {"adaptive": "C", "adaptive_learned": "G", J: "J"}


def escapes(rows, ctrls=CONTROLLERS):
    return [r for r in rows if r["controller"] in ctrls and r["success"] != "True"
            and r["protective_stop"] != "True" and r["declared_success"] != "False"]


def last(ev, kind):
    hits = [e[2] for e in ev if e[1] == kind]
    return hits[-1] if hits else ""


def seat(ev, ctrl):
    if ctrl == J:
        return last(ev, "verify_handover").split(": C's VERIFY")[0]
    cand = next((e[2] for e in reversed(ev) if "seated_candidate" in str(e[2])), "")
    return cand.split(" Fax")[0].replace("seated_candidate ", "")


def key(r):
    return f"{r['condition']}|{r['controller']}|{r['trial_index']}"


def escape_row(run, r, ev):
    wy = last(ev, "wall_yaw").split(", levers")[0] or "not used"
    return (f"| {run} | {LABEL[r['controller']]} | {r['condition']} | {r['trial_index']} | "
            f"{float(r['final_depth_mm']):.2f} | {float(r['final_tilt_deg']):.2f} | "
            f"{float(r['final_yaw_deg']):.2f} | {seat(ev, r['controller'])} | {wy} |")


def wall_yaw_counts(run, events, ctrls, counts):
    for k, ev in events.items():
        ctrl = k.split("|")[1]
        if ctrl not in ctrls:
            continue
        for e in ev:
            if e[1] == "wall_yaw" and "PASS" in e[2]:
                m = re.search(r">= (-?[\d.]+)", e[2])
                neg = bool(m and float(m.group(1)) < 0)
                counts[(run, LABEL[ctrl], "passes")] += 1
                counts[(run, LABEL[ctrl], "negative")] += neg


ESCAPE_HEADER = ("| Run | Ctrl | Condition | Trial | Depth (mm, true) | Tilt (deg) | Yaw (deg) | Seat candidate | "
                 "Wall-yaw check |\n|---|---|---|---|---|---|---|---|---|")
WALL_YAW_HEADER = "| Run | Ctrl | Wall-yaw passes | Required travel < 0 |\n|---|---|---|---|"


def wall_yaw_table(counts):
    print(WALL_YAW_HEADER)
    for run, ctrl in sorted({(k[0], k[1]) for k in counts}):
        print(f"| {run} | {ctrl} | {counts[(run, ctrl, 'passes')]} | {counts[(run, ctrl, 'negative')]} |")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("root", type=Path)
    a = ap.parse_args()
    print(f"# Audit tables for {a.root.name}\n")
    print(f"Generated by `python -m experiments.cp2_audit {a.root}`.\n")
    print("## Every bad unit C or G passed\n")
    print(ESCAPE_HEADER)
    vacuous, j_vacuous, j_rows, j_runs = Counter(), Counter(), [], []
    for run in sorted(p.name for p in a.root.iterdir() if (p / "trials.csv").exists()):
        rows = list(csv.DictReader(open(a.root / run / "trials.csv")))
        evp = a.root / run / "events.json.gz"
        events = json.load(gzip.open(evp)) if evp.exists() else {}
        for r in escapes(rows):
            print(escape_row(run, r, events.get(key(r), [])))
        wall_yaw_counts(run, events, CONTROLLERS, vacuous)
        if any(r["controller"] == J for r in rows):
            j_runs.append(run)
            j_rows += [escape_row(run, r, events.get(key(r), [])) for r in escapes(rows, (J,))]
            wall_yaw_counts(run, events, (J,), j_vacuous)
    print("\n## Wall-yaw passes where the required free travel was negative (no constraint)\n")
    wall_yaw_table(vacuous)
    if not j_runs:
        return
    print("\n## Every bad unit J passed\n")
    print(f"J runs C's VERIFY after F's insertion. Runs with J: {', '.join(j_runs)}. Seat candidate: F's hand-over "
          f"to C's VERIFY (depth reading, and the face contact C's VERIFY uses as the mouth plane).\n")
    print(ESCAPE_HEADER)
    print("\n".join(j_rows) if j_rows else "| none | | | | | | | | |")
    print("\n## J: wall-yaw passes where the required free travel was negative (no constraint)\n")
    wall_yaw_table(j_vacuous)


if __name__ == "__main__":
    main()
