"""Audit of C's and G's escapes in a benchmark folder: final pose and the seat and verify events.

python -m experiments.cp2_audit results/benchmark_v0.2b > results/benchmark_v0.2b/AUDIT_TABLES.md
"""
from __future__ import annotations

import argparse
import csv
import gzip
import json
import re
from collections import Counter
from pathlib import Path

CONTROLLERS = ("adaptive", "adaptive_learned")
LABEL = {"adaptive": "C", "adaptive_learned": "G"}


def escapes(rows):
    return [r for r in rows if r["controller"] in CONTROLLERS and r["success"] != "True"
            and r["protective_stop"] != "True" and r["declared_success"] != "False"]


def last(ev, kind):
    hits = [e[2] for e in ev if e[1] == kind]
    return hits[-1] if hits else ""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("root", type=Path)
    a = ap.parse_args()
    print(f"# Audit tables for {a.root.name}\n")
    print(f"Generated by `python -m experiments.cp2_audit results/{a.root.name}`.\n")
    print("## Every bad unit C or G passed\n")
    print("| Run | Ctrl | Condition | Trial | Depth (mm, true) | Tilt (deg) | Yaw (deg) | Seat candidate | Wall-yaw check |")
    print("|---|---|---|---|---|---|---|---|---|")
    vacuous = Counter()
    for run in sorted(p.name for p in a.root.iterdir() if (p / "trials.csv").exists()):
        rows = list(csv.DictReader(open(a.root / run / "trials.csv")))
        evp = a.root / run / "events.json.gz"
        events = json.load(gzip.open(evp)) if evp.exists() else {}
        for r in escapes(rows):
            ev = events.get(f"{r['condition']}|{r['controller']}|{r['trial_index']}", [])
            cand = next((e[2] for e in reversed(ev) if "seated_candidate" in str(e[2])), "")
            cand = cand.split(" Fax")[0].replace("seated_candidate ", "")
            wy = last(ev, "wall_yaw").split(", levers")[0] or "not used"
            print(f"| {run} | {LABEL[r['controller']]} | {r['condition']} | {r['trial_index']} | "
                  f"{float(r['final_depth_mm']):.2f} | {float(r['final_tilt_deg']):.2f} | "
                  f"{float(r['final_yaw_deg']):.2f} | {cand} | {wy} |")
        for k, ev in events.items():
            ctrl = k.split("|")[1]
            if ctrl not in CONTROLLERS:
                continue
            for e in ev:
                if e[1] == "wall_yaw" and "PASS" in e[2]:
                    m = re.search(r">= (-?[\d.]+)", e[2])
                    neg = bool(m and float(m.group(1)) < 0)
                    vacuous[(run, LABEL[ctrl], "passes")] += 1
                    vacuous[(run, LABEL[ctrl], "negative")] += neg
    print("\n## Wall-yaw passes where the required free travel was negative (no constraint)\n")
    print("| Run | Ctrl | Wall-yaw passes | Required travel < 0 |")
    print("|---|---|---|---|")
    for run, ctrl in sorted({(k[0], k[1]) for k in vacuous}):
        print(f"| {run} | {ctrl} | {vacuous[(run, ctrl, 'passes')]} | {vacuous[(run, ctrl, 'negative')]} |")


if __name__ == "__main__":
    main()
