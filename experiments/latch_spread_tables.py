"""Tables for the latch-spread check on the Checkpoint 2 code (results/v0.2b_latch_spread).

python -m experiments.latch_spread_tables > results/v0.2b_latch_spread/tables.md
"""
from __future__ import annotations

import csv
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "results" / "v0.2b_latch_spread"
GOOD = ("mf_nominal", "mf_moderate", "mf_noise_1mm")
CTRL = (("adaptive", "C"), ("adaptive_learned", "G"), ("spiral", "D"), ("spiral_rcc", "F"))


def main() -> None:
    settings = [l.split() for l in (ROOT / "settings.txt").read_text().splitlines() if l.strip()]
    print("# Latch-spread check, Checkpoint 2 code, dev seed 2027\n")
    print("Generated by `python -m experiments.latch_spread_tables`. Simulator-side spread only; the controllers "
          "keep the connector file's values. 20 trials per condition: 60 good parts, 80 bad parts per cell.\n")
    print("| Backend | Spread | " + " | ".join(f"{l} good seated" for _, l in CTRL) + " | "
          + " | ".join(f"{l} bad passed" for _, l in CTRL) + " | C good-part failures |")
    print("|---|---|" + "---|" * (2 * len(CTRL) + 1))
    for s in settings:
        backend, name = s[0], s[1]
        rows = list(csv.DictReader((ROOT / f"{backend}_{name}" / "trials.csv").open()))
        good = [r for r in rows if r["condition"] in GOOD]
        bad = [r for r in rows if r["condition"] not in GOOD]
        seat = [sum(r["success"] == "True" for r in good if r["controller"] == c) for c, _ in CTRL]
        esc = [sum(r["success"] != "True" and r["protective_stop"] != "True" and r["declared_success"] != "False"
                   for r in bad if r["controller"] == c) for c, _ in CTRL]
        why = Counter(r["failure_reason"] for r in good if r["controller"] == "adaptive" and r["success"] != "True")
        print(f"| {backend} | {' '.join(s[2:])} | " + " | ".join(f"{v}/60" for v in seat) + " | "
              + " | ".join(f"{v}/80" for v in esc) + " | " + ", ".join(f"{k} {v}" for k, v in why.most_common(3)) + " |")


if __name__ == "__main__":
    main()
