"""Regenerate the README results block from a benchmark's summary.json.

Every number between ``<!-- RESULTS:START -->`` and ``<!-- RESULTS:END -->`` comes
from ``results/<name>/summary.json`` and ``config.json``; nothing is typed by hand.

    python -m experiments.readme_results results/benchmark_v0.2a
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from defex.config import REPO_ROOT
from experiments.evaluate import CONTROLLER_ORDER, LABELS

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def _p(p: float) -> str:
    return "<1e-6" if p < 1e-6 else f"{p:.2g}"


def render(run_dir: Path) -> str:
    summ = json.loads((run_dir / "summary.json").read_text())
    cfg = json.loads((run_dir / "config.json").read_text())
    rel = run_dir.relative_to(REPO_ROOT)
    overall = {o["controller"]: o for o in summ["overall"]}
    paired = summ.get("paired_vs_adaptive", {})
    ctrls = [c for c in CONTROLLER_ORDER if c in overall]
    n = cfg["n_trials_per_condition"]
    n_cond = len(cfg["conditions"])
    env = cfg["environment"]
    reset = next(iter(overall.values()))["stop_reset_s"]
    lines = [
        f"Source: [`{rel}`]({rel}) (seed {cfg['base_seed']}, commit `{env['git_commit'][:7]}`, "
        f"{n_cond} conditions x {n} paired trials per controller; pre-registration in "
        f"[`PREREGISTRATION.md`]({rel}/PREREGISTRATION.md)). Generated by `python -m experiments.readme_results {rel}`.",
        "",
        f"![Benchmark dashboard]({rel}/plots/dashboard_light.png)",
        "",
        "| Controller | Success (95% CI) | Bad units passed | Detected failures | Protective stops | "
        "False accepts | Cycle p50 / p95 / p99, successes (s) | Good units per hour, no reset / "
        f"{reset:g} s per stop | p95 peak contact force (N) | Paired vs C: C-only / other-only (McNemar p) |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for c in ctrls:
        o = overall[c]
        ct = o["cycle_time_s_success"]
        pr = paired.get(c)
        pair = "reference" if c == "adaptive" else (
            f"{pr['reference_only_success']} / {pr['controller_only_success']} ({_p(pr['mcnemar_p'])})" if pr else "n/a"
        )
        fa = str(o["false_accepts"]) if o["self_checks"] else "n/a (no self-check)"
        lines.append(
            f"| {LABELS[c]} | {_pct(o['success_rate'])} ({_pct(o['success_ci_low'])}-{_pct(o['success_ci_high'])}) | "
            f"{o['escapes']} | {o['detected_failures']} | {o['protective_stops']} | {fa} | "
            f"{ct['median']:.2f} / {ct['p95']:.2f} / {ct['p99']:.2f} | "
            f"{o['throughput_uph_no_reset']:.0f} / {o['throughput_uph_with_reset']:.0f} | "
            f"{o['peak_contact_force_n']['p95']:.1f} | {pair} |"
        )
    lines += [
        "",
        f"*Bad units passed*: the trial failed, the cell did not stop and the controller did not declare failure, so the "
        f"part leaves the cell as if it were good. *Good units per hour*: successes per hour of simulated cell time, "
        f"counting failed cycles; the second figure adds an assumed {reset:g} s of operator time per protective stop.",
        "",
        "Success per condition (95% Wilson interval in brackets):",
        "",
        "| Condition | " + " | ".join(LABELS[c] for c in ctrls) + " |",
        "|---|" + "---|" * len(ctrls),
    ]
    cells = {(s["condition"], s["controller"]): s for s in summ["summary"]}
    for cond in [c["name"] for c in cfg["conditions"]]:
        row = []
        for c in ctrls:
            s = cells.get((cond, c))
            row.append("" if s is None else
                       f"{s['success_rate'] * 100:.0f}% ({s['success_ci_low'] * 100:.0f}-{s['success_ci_high'] * 100:.0f})")
        lines.append(f"| {cond} | " + " | ".join(row) + " |")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("run_dir", type=Path)
    ap.add_argument("--readme", type=Path, default=REPO_ROOT / "README.md")
    args = ap.parse_args()
    run_dir = args.run_dir.resolve()
    text = args.readme.read_text()
    a, b = text.index(START) + len(START), text.index(END)
    args.readme.write_text(text[:a] + "\n" + render(run_dir) + "\n" + text[b:])
    print(f"updated {args.readme} from {run_dir / 'summary.json'}")


if __name__ == "__main__":
    main()
