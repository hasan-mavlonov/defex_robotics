"""Before/after tables for the v0.2c gantry re-tune (dev seed 2027).

python -m experiments.v02c_gantry_tables > results/v0.2c_gantry_baselines/tables.md
"""
from __future__ import annotations

import csv
from math import comb
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "results" / "v0.2c_gantry_baselines"
NAMES = {"fixed": "A", "correction": "B", "adaptive": "C", "spiral": "D", "correction_rcc": "E",
         "spiral_rcc": "F", "adaptive_learned": "G"}
GOOD_LATCH = {"mf_nominal", "mf_moderate", "mf_noise_1mm"}


def mcnemar(b: int, c: int) -> float:
    n = b + c
    return 1.0 if n == 0 else min(1.0, 2 * sum(comb(n, i) for i in range(min(b, c) + 1)) / 2 ** n)


def load(stage: str, run: str) -> dict:
    rows = csv.DictReader((ROOT / stage / run / "trials.csv").open())
    return {(r["controller"], r["condition"], r["trial_index"]): r for r in rows}


def ok(r) -> bool:
    return r["success"] == "True"


def escape(r) -> bool:
    return not ok(r) and r["protective_stop"] != "True" and r["declared_success"] != "False"


def uph(rs, reset_s=60.0) -> float:
    busy = sum(float(r["cycle_time_s"]) for r in rs) + reset_s * sum(r["protective_stop"] == "True" for r in rs)
    return 3600.0 * sum(ok(r) for r in rs) / busy


def median(xs):
    xs = sorted(xs)
    return xs[len(xs) // 2] if xs else float("nan")


def table(title: str, run: str, keep) -> None:
    b, a = load("before", run), load("after", run)
    print(f"## {title}\n")
    print("| Controller | Success before -> after | Lost / gained (p) | After vs C: C-only / other-only (p) | "
          "Escapes before -> after | Stops before -> after | Median good cycle (s) | Good units/h, 60 s per stop |")
    print("|---|---|---|---|---|---|---|---|")
    for ctrl, lab in NAMES.items():
        keys = [k for k in b if k[0] == ctrl and keep(k[1])]
        if not keys:
            continue
        rb, ra = [b[k] for k in keys], [a[k] for k in keys]
        lost = sum(ok(x) and not ok(y) for x, y in zip(rb, ra))
        gained = sum(ok(y) and not ok(x) for x, y in zip(rb, ra))
        ck = [("adaptive",) + k[1:] for k in keys]
        c_only = sum(ok(a[c]) and not ok(a[k]) for c, k in zip(ck, keys))
        o_only = sum(ok(a[k]) and not ok(a[c]) for c, k in zip(ck, keys))
        vs = "-" if ctrl == "adaptive" else f"{c_only} / {o_only} ({mcnemar(c_only, o_only):.2g})"
        cyc = lambda rs: median([float(r["cycle_time_s"]) for r in rs if ok(r)])
        print(f"| {lab} {ctrl} | {sum(map(ok, rb))} -> {sum(map(ok, ra))} of {len(keys)} | {lost} / {gained} "
              f"({mcnemar(lost, gained):.2g}) | {vs} | {sum(map(escape, rb))} -> {sum(map(escape, ra))} | "
              f"{sum(r['protective_stop'] == 'True' for r in rb)} -> {sum(r['protective_stop'] == 'True' for r in ra)} | "
              f"{cyc(rb):.2f} -> {cyc(ra):.2f} | {uph(rb):.0f} -> {uph(ra):.0f} |")
    print()


def main() -> None:
    print("# v0.2c gantry re-tune: before (0300106) / after (0ae06ba), dev seed 2027\n")
    print("Generated by `python -m experiments.v02c_gantry_tables`. Escapes = failed, not stopped, not declared "
          "failed. Throughput counts every cycle of the rows in the table plus 60 s per protective stop.\n")
    table("Standard suite, 20 conditions x 10 trials", "gantry_dev2027_standard", lambda c: True)
    table("Latching suite, good parts (3 conditions x 20 trials)", "gantry_dev2027_latching", lambda c: c in GOOD_LATCH)
    table("Latching suite, deliberately bad parts (4 x 20): success is 0 by design; read escapes",
          "gantry_dev2027_latching", lambda c: c not in GOOD_LATCH)


if __name__ == "__main__":
    main()
