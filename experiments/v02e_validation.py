"""v0.2e validation on seed 4006: paired before (v0.2d code) / after (v0.2e code), rule in
results/v0.2e_validation/VALIDATION_RULE.md.

    python -m experiments.v02e_validation results/v0.2e_validation
"""
import csv
import sys
from pathlib import Path

from experiments.checkpoint_report import escape, mcnemar, ok

LETTER = {"fixed": "A", "correction": "B", "adaptive": "C", "spiral": "D", "correction_rcc": "E",
          "spiral_rcc": "F", "adaptive_learned": "G", "spiral_pull": "H", "spiral_rcc_pull": "I",
          "spiral_rcc_verify": "J"}
FIXES = [("1 simulator reset", list(LETTER)),
         ("2 H/I pull retry v5", ["spiral_pull", "spiral_rcc_pull"]),
         ("3 tilt-check force guard", ["adaptive", "adaptive_learned", "spiral_rcc_verify"])]
OUTCOME = ("success", "declared_success", "protective_stop")


def load(folder: Path) -> dict:
    rows = {}
    for run in sorted(folder.iterdir()):
        f = run / "trials.csv"
        if not f.exists():
            continue
        machine, suite = run.name.split("_", 1)
        for r in csv.DictReader(open(f)):
            key = (machine, suite, r["controller"], r["condition"], r["trial_index"])
            assert key not in rows, key
            rows[key] = r
    return rows


def fmt_p(p: float) -> str:
    return "< 1e-6" if p < 1e-6 else f"{p:.2g}"


def main(root: Path) -> None:
    before, after = load(root / "before"), load(root / "after")
    assert before.keys() == after.keys(), "before and after are not the same trials"
    print("# v0.2e validation tables (seed 4006)\n")
    print(f"Generated by `python -m experiments.v02e_validation {root}`; {len(before)} paired trials.\n")
    print("Per controller and machine, pooled over the four suites. Good = good-part trials "
          "(group not `bad_part`); bad units = escapes on good-part trials; bad parts = escapes on "
          "`bad_part` trials. Lost / gained = before-only / after-only.\n")
    print("| Machine | Ctrl | Good seated before -> after | Lost / gained | p | Bad parts before -> after | p "
          "| Bad units before -> after | p | Outcome changes | Rows changed |")
    print("|---|---|---|---|---|---|---|---|---|---|---|")
    stats = {}
    for machine in ("gantry", "arm"):
        for ctl in LETTER:
            keys = [k for k in before if k[0] == machine and k[2] == ctl]
            good = [k for k in keys if before[k]["group"] != "bad_part"]
            bad = [k for k in keys if before[k]["group"] == "bad_part"]
            lost = sum(ok(before[k]) and not ok(after[k]) for k in good)
            gained = sum(ok(after[k]) and not ok(before[k]) for k in good)
            bp = [sum(escape(d[k]) for k in bad) for d in (before, after)]
            bp_up = sum(escape(after[k]) and not escape(before[k]) for k in bad)
            bp_dn = sum(escape(before[k]) and not escape(after[k]) for k in bad)
            bu = [sum(escape(d[k]) for k in good) for d in (before, after)]
            bu_up = sum(escape(after[k]) and not escape(before[k]) for k in good)
            bu_dn = sum(escape(before[k]) and not escape(after[k]) for k in good)
            oc = sum(any(before[k][f] != after[k][f] for f in OUTCOME) for k in keys)
            rc = sum(any(before[k][f] != after[k][f] for f in before[k] if f != "wall_time_s") for k in keys)
            s = dict(lost=lost, gained=gained, p_seat=mcnemar(lost, gained), bp_up=bp_up, bp_dn=bp_dn,
                     p_bp=mcnemar(bp_up, bp_dn), bu_up=bu_up, bu_dn=bu_dn, p_bu=mcnemar(bu_up, bu_dn), oc=oc)
            stats[(machine, ctl)] = s
            seated = [sum(ok(d[k]) for k in good) for d in (before, after)]
            print(f"| {machine} | {LETTER[ctl]} | {seated[0]} -> {seated[1]} of {len(good)} | {lost} / {gained} | "
                  f"{fmt_p(s['p_seat'])} | {bp[0]} -> {bp[1]} of {len(bad)} | {fmt_p(s['p_bp'])} | "
                  f"{bu[0]} -> {bu[1]} | {fmt_p(s['p_bu'])} | {oc} | {rc} of {len(keys)} |")
    print("\n## Rule, per fix\n")
    print("| Fix | Controllers | Failing conditions | Verdict |")
    print("|---|---|---|---|")
    for name, ctls in FIXES:
        fails = []
        for machine in ("gantry", "arm"):
            for ctl in ctls:
                s = stats[(machine, ctl)]
                tag = f"{machine} {LETTER[ctl]}"
                if s["lost"] > s["gained"] and s["p_seat"] < 0.05:
                    fails.append(f"{tag}: fewer seated, p = {fmt_p(s['p_seat'])}")
                if s["bp_up"] > s["bp_dn"] and s["p_bp"] < 0.05:
                    fails.append(f"{tag}: more bad parts, p = {fmt_p(s['p_bp'])}")
                if s["bu_up"] > s["bu_dn"] and s["p_bu"] < 0.05:
                    fails.append(f"{tag}: more bad units, p = {fmt_p(s['p_bu'])}")
        print(f"| {name} | {', '.join(LETTER[c] for c in ctls)} | {'; '.join(fails) or 'none'} | "
              f"{'not kept' if fails else 'kept'} |")
    others = [c for c in LETTER if c not in sum((f[1] for f in FIXES[1:]), [])]
    oc = {f"{m} {LETTER[c]}": stats[(m, c)]["oc"] for m in ("gantry", "arm") for c in others}
    print(f"\nControllers touched only by fix 1 ({', '.join(LETTER[c] for c in others)}), trials with an outcome "
          f"change: {sum(oc.values())} ({', '.join(f'{k} {v}' for k, v in oc.items() if v) or 'none'}).")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
