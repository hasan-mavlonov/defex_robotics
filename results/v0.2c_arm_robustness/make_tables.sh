#!/usr/bin/env bash
# Regenerates tables.md from the committed trials.csv files. Run from the repository root.
set -euo pipefail
PY=${PY:-python}
R=results/v0.2c_arm_robustness
{
echo "# v0.2c arm robustness: tables"
echo
echo "Generated by results/v0.2c_arm_robustness/make_tables.sh from committed files. Development measurements in simulation."
echo "Before = commit 54f3097 (untouched v0.2/checkpoint2). After = commit a5bd452."
echo
echo "## Gantry and baseline equivalence (scripts/compare_trials.py, wall_time_s ignored)"
echo
echo '```'
for s in gantry_rule3_standard_seed2026 gantry_rule3_latching_seed2026 arm_standard5_seed2026 arm_latching_baselines_seed2026; do
  $PY scripts/compare_trials.py $R/before/$s/trials.csv $R/after_a5bd452/$s/trials.csv 2>&1 | head -1 || true  # whole file; arm_standard5 includes C and G, which are meant to change
done
echo "(arm_standard5_seed2026 holds C and G too, which are meant to change; per-controller comparisons follow.)"
for c in fixed correction spiral correction_rcc spiral_rcc; do
  for s in arm_standard5_seed2026 arm_latching_baselines_seed2026; do
    printf "%s %s: " $c $s
    $PY scripts/compare_trials.py $R/before/$s/trials.csv $R/after_a5bd452/$s/trials.csv --pair $c,$c 2>&1 | head -1 | sed 's/.*: //'
  done
done
echo '```'
echo
for seed in 2026 2027; do
  echo "## Arm, seed $seed: C before -> after"
  echo
  for s in arm_standard5 arm_latching; do
    $PY -m experiments.v02c_tables $R/before/${s}_seed$seed:adaptive $R/after_a5bd452/${s}_seed$seed:adaptive
  done
done
echo "## Arm, seed 2027, all 20 standard conditions x 5 trials: C before -> after"
echo
$PY -m experiments.v02c_tables $R/before/arm_standard_all_seed2027:adaptive $R/after_a5bd452/arm_standard_all_seed2027:adaptive
for seed in 2026 2027; do
  echo "## Arm, seed $seed: G (adaptive_learned) before -> after (G inherits C's changes)"
  echo
  for s in arm_standard5 arm_latching; do
    $PY -m experiments.v02c_tables $R/before/${s}_seed$seed:adaptive_learned $R/after_a5bd452/${s}_seed$seed:adaptive_learned
  done
done
echo "## Development, seed 2026, 60 trials: one rule off at a time (commit 110f7e1)"
echo
for c in noise_1mm noise_2mm friction_1; do $PY -m experiments.v02c_ablation $R/dev2026/ablation2_${c}_110f7e1 | grep -v "| $c |"; echo; done
$PY -m experiments.v02c_ablation $R/dev2026/ablation2_latching_110f7e1 | grep -v "| mf_noise_1mm |"; echo
$PY -m experiments.v02c_ablation $R/dev2026/ablation_latching_75e1585 | grep -v "| mf_noise_1mm |"; echo
echo "## Failure classes of C on the arm (experiments/c_arm_failures.py)"
echo
echo '```'
$PY -m experiments.c_arm_failures $R/before/arm_standard5_seed2026 $R/after_a5bd452/arm_standard5_seed2026 $R/before/arm_standard5_seed2027 $R/after_a5bd452/arm_standard5_seed2027 $R/before/arm_latching_seed2027 $R/after_a5bd452/arm_latching_seed2027
echo '```'
} > $R/tables.md
