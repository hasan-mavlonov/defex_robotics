#!/usr/bin/env bash
# Each workstream's committed after-runs against the same runs on the integrated code (LABEL, default
# claims_merged). Writes results/v0.2c_integration/$LABEL/comparison.md.
set -euo pipefail
cd "$(dirname "$0")/../.."
PY=${PY:-$HOME/projects/defex_robotics/.venv/bin/python}
L=${LABEL:-claims_merged}
M=results/v0.2c_integration/$L
AB=results/v0.2c_arm_baselines/after
RB=results/v0.2c_arm_robustness/after_a5bd452
DV=results/v0.2c_defect_verdict/after
{
echo "# $L: workstream after-runs (A) against the integrated code (B)"
echo
echo "Generated by results/v0.2c_integration/claims_tables.sh (experiments/v02c_integration_compare.py). Trials matched on"
echo "condition, trial index and seed; a shorter run is compared with the first trials of a longer one."
echo
echo "## arm-baselines (D, E, F tuned on the arm; after = e054ff0)"
$PY -m experiments.v02c_integration_compare \
  $AB/gantry_rule3_standard $M/gantry_rule3_standard $AB/gantry_rule3_latching $M/gantry_rule3_latching \
  $AB/arm_dev2026_standard5 $M/arm_dev2026_standard5 $AB/arm_dev2026_latching $M/arm_dev2026_latching \
  $AB/arm_dev2027_standard5 $M/arm_dev2027_standard5 $AB/arm_dev2027_latching $M/arm_dev2027_latching \
  $AB/arm_dev2027_standard20 $M/arm_dev2027_standard20
echo "## arm-robustness (C on the arm; after = a5bd452)"
$PY -m experiments.v02c_integration_compare --controllers adaptive,adaptive_learned \
  $RB/gantry_rule3_standard_seed2026 $M/gantry_rule3_standard $RB/gantry_rule3_latching_seed2026 $M/gantry_rule3_latching \
  $RB/arm_standard5_seed2026 $M/arm_dev2026_standard5 $RB/arm_latching_seed2026 $M/arm_latching_s2026 \
  $RB/arm_standard5_seed2027 $M/arm_dev2027_standard5 $RB/arm_latching_seed2027 $M/arm_latching_s2027 \
  $RB/arm_standard_all_seed2027 $M/arm_dev2027_standard20
echo "## defect-verdict (C on latching parts; after = afa08a4)"
$PY -m experiments.v02c_integration_compare \
  $DV/gantry_latching_s2026 $M/gantry_latching_s2026 $DV/gantry_latching_s2027 $M/gantry_latching_s2027 \
  $DV/arm_latching_s2026 $M/arm_latching_s2026 $DV/arm_latching_s2027 $M/arm_latching_s2027 \
  $DV/gantry_standard_cg $M/gantry_standard_cg $DV/arm_standard_cg $M/arm_standard_cg
} > $M/comparison.md
